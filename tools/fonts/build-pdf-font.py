#!/usr/bin/env python3
"""Regenerate src/shared/utils/pdfFont.ts — the Roboto subset embedded in PDF exports.

jsPDF's built-in Helvetica has no Czech/Slovak diacritics and no Cyrillic, so the
exports embed a small Roboto subset (Apache-2.0). Input: the Roboto *variable*
font (googlefonts/roboto-3, e.g. Roboto[wdth,wght].ttf — Android Studio ships it
as layoutlib/data/fonts/Roboto-Regular.ttf). Needs fonttools (`pip install fonttools`).

    python3 tools/fonts/build-pdf-font.py path/to/Roboto-variable.ttf
"""
import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

# Basic Latin + Latin-1 + Latin Extended-A (cs/sk: č ř ž ľ ĺ ŕ ô ä …),
# Cyrillic for Ukrainian (А–я, Ё/ё, Є/є, І/і, Ї/ї, Ґ/ґ), Σ, and typographic marks.
UNICODES = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x180))
    + list(range(0x400, 0x460))
    + [0x490, 0x491, 0x3A3, 0x2116]
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026, 0x2212]
)

OUT = Path(__file__).resolve().parents[2] / 'src/shared/utils/pdfFont.ts'


def build(src: str, weight: int) -> str:
    font = TTFont(src)
    static = instancer.instantiateVariableFont(font, {'wght': weight, 'wdth': 100, 'ital': 0})
    opts = subset.Options()
    opts.layout_features = ['kern']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(static)
    buf = io.BytesIO()
    static.save(buf)
    return base64.b64encode(buf.getvalue()).decode('ascii')


def main() -> None:
    src = sys.argv[1]
    regular, bold = build(src, 400), build(src, 700)
    OUT.write_text(f"""// AUTO-GENERATED by tools/fonts/build-pdf-font.py — do not edit by hand.
// Subset of Roboto (Apache-2.0) covering Basic Latin + Latin-1 + Latin
// Extended-A (Czech/Slovak diacritics) + Cyrillic (Ukrainian) + the symbols used
// in exports (— · − × Σ „“ № …). Embedded so jsPDF renders cs/sk/uk correctly
// (its built-in Helvetica cannot).
import type {{ jsPDF }} from 'jspdf';

const ROBOTO_REGULAR = '{regular}';
const ROBOTO_BOLD = '{bold}';

/**
 * Register the embedded Roboto subset on a jsPDF document and make it active.
 * jsPDF's virtual file system is per-document, so call this once per new jsPDF.
 * Pass font 'Roboto' in jspdf-autotable styles to use it in tables too.
 */
export function registerPdfFont(doc: jsPDF): string {{
    doc.addFileToVFS('Roboto-Regular.ttf', ROBOTO_REGULAR);
    doc.addFont('Roboto-Regular.ttf', 'Roboto', 'normal');
    doc.addFileToVFS('Roboto-Bold.ttf', ROBOTO_BOLD);
    doc.addFont('Roboto-Bold.ttf', 'Roboto', 'bold');
    doc.setFont('Roboto', 'normal');
    return 'Roboto';
}}
""")
    print(f'wrote {OUT} (regular {len(regular)} b64 chars, bold {len(bold)})')


if __name__ == '__main__':
    main()
